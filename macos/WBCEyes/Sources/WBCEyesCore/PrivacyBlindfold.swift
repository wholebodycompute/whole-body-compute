import Foundation

/// Native Swift Blood-Brain Barrier blindfold enforced inside `WBC Eyes.app`
/// BEFORE returning any UI snapshot bytes or posting any `AXUIElement` / `CGEvent` actuation.
public enum PrivacyBlindfold {

    public enum BlockCategory: String, Sendable, Equatable {
        case secureVault = "secure_vault"
        case systemSecuritySurface = "system_security_surface"
        case sensitiveWebOrigin = "sensitive_web_origin"
        case secureTextField = "secure_text_field"
    }

    public struct BlindfoldDecision: Sendable, Equatable {
        public let blocked: Bool
        public let category: BlockCategory?
        public let placeholderTitle: String
        public let reason: String

        public static let allowed = BlindfoldDecision(
            blocked: false,
            category: nil,
            placeholderTitle: "",
            reason: ""
        )
    }

    public static let blockedPasswordManagerNames: Set<String> = [
        "1password",
        "1password 7",
        "1password 8",
        "bitwarden",
        "lastpass",
        "keepass",
        "keepassxc",
        "keychain access",
        "dashlane",
        "nordpass",
        "authy",
        "authenticator",
        "yubikey",
        "enpass",
        "roboform",
        "passwords.app",
        "apple passwords"
    ]

    public static let exactBlockedVaultAppNames: Set<String> = [
        "passwords",
        "keychain"
    ]

    public static let blockedVaultBundleIDPrefixes: [String] = [
        "com.1password.",
        "com.agilebits.onepassword",
        "com.bitwarden.",
        "com.apple.passwords",
        "com.apple.keychainaccess",
        "com.lastpass.",
        "org.keepassxc.",
        "com.dashlane.",
        "com.nordpass.",
        "com.authy.",
        "com.yubico.",
        "in.sinew.enpass",
        "com.siber.roboform"
    ]

    public static let blockedSystemSecurityAppNames: Set<String> = [
        "system settings",
        "system preferences",
        "securityagent",
        "coreservicesuiagent",
        "universalaccessauthwarn",
        "userauthenticationagent",
        "localauthenticationremoteservice",
        "tccd"
    ]

    public static let blockedSystemSecurityBundleIDPrefixes: [String] = [
        "com.apple.systempreferences",
        "com.apple.securityagent",
        "com.apple.universalaccessauthwarn",
        "com.apple.coreservices.uiagent",
        "com.apple.coreservicesuiagent",
        "com.apple.userauthenticationagent",
        "com.apple.localauthentication"
    ]

    public static let sensitiveWebOriginPatterns: [String] = [
        "my.1password.com",
        "1password.com",
        "vault.bitwarden.com",
        "bitwarden.com",
        "lastpass.com",
        "app.dashlane.com",
        "nordpass.com",
        "icloud.com/passwords",
        "console.aws.amazon.com/iam",
        "signin.aws.amazon.com"
    ]

    public static let concealedPasteboardTypes: Set<String> = [
        "org.nspasteboard.concealedtype",
        "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype",
        "com.agilebits.onepassword",
        "de.petermaurer.transientpasteboardtype"
    ]

    private static let secretRegexes: [NSRegularExpression] = {
        let patterns = [
            #"sk-(?:proj-|ant-|live-|test-)?[A-Za-z0-9_\-]{16,}"#,
            #"gh[pousr]_[A-Za-z0-9]{20,}"#,
            #"github_pat_[A-Za-z0-9_]{24,}"#,
            #"AKIA[0-9A-Z]{16}"#,
            #"xox[baprs]-[A-Za-z0-9\-]{16,}"#,
            #"hf_[A-Za-z0-9]{20,}"#,
            #"phc_[A-Za-z0-9]{20,}"#,
            #"SG\.[A-Za-z0-9_\-]{12,}\.[A-Za-z0-9_\-]{16,}"#,
            #"eyJ[A-Za-z0-9_\-]{10,}\.eyJ[A-Za-z0-9_\-]{10,}\.[A-Za-z0-9_\-]{10,}"#,
            #"(?i)(?:bearer\s+)[A-Za-z0-9._\-]{20,}"#,
            #"(?i)(?:password|passwd|api_key|secret|token)\s*=\s*[^\s&\"']+"#
        ]
        return patterns.compactMap { try? NSRegularExpression(pattern: $0) }
    }()

    /// Evaluate app-level blindfolds (password vaults & macOS TCC/System Settings surfaces).
    public static func checkApplication(appName: String, bundleID: String) -> BlindfoldDecision {
        let normApp = appName.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        let normBundle = bundleID.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()

        // 1. Password Vaults
        if !normBundle.isEmpty {
            for prefix in blockedVaultBundleIDPrefixes where normBundle == prefix || normBundle.hasPrefix(prefix) {
                return BlindfoldDecision(
                    blocked: true,
                    category: .secureVault,
                    placeholderTitle: "[BLOCKED_SECURE_VAULT]",
                    reason: "BLOCKED: Application '\(appName.isEmpty ? bundleID : appName)' is a protected password vault."
                )
            }
        }
        if !normApp.isEmpty {
            if exactBlockedVaultAppNames.contains(normApp)
                || blockedPasswordManagerNames.contains(where: { normApp.contains($0) })
            {
                return BlindfoldDecision(
                    blocked: true,
                    category: .secureVault,
                    placeholderTitle: "[BLOCKED_SECURE_VAULT]",
                    reason: "BLOCKED: Application '\(appName)' is an auth vault or password manager."
                )
            }
        }

        // 2. macOS System Settings / SecurityAgent / TCC Prompt Surfaces
        if !normBundle.isEmpty {
            for prefix in blockedSystemSecurityBundleIDPrefixes where normBundle == prefix || normBundle.hasPrefix(prefix) {
                return BlindfoldDecision(
                    blocked: true,
                    category: .systemSecuritySurface,
                    placeholderTitle: "[BLOCKED_SYSTEM_SECURITY_SURFACE]",
                    reason: "BLOCKED: Application '\(appName.isEmpty ? bundleID : appName)' is a protected macOS system/security surface."
                )
            }
        }
        if !normApp.isEmpty {
            if blockedSystemSecurityAppNames.contains(where: { normApp == $0 || normApp.contains($0) }) {
                return BlindfoldDecision(
                    blocked: true,
                    category: .systemSecuritySurface,
                    placeholderTitle: "[BLOCKED_SYSTEM_SECURITY_SURFACE]",
                    reason: "BLOCKED: Application '\(appName)' is a protected macOS system/security surface."
                )
            }
        }

        return .allowed
    }

    /// Evaluate window/web-origin blindfolds across AXTitle, AXDocument, and AXWebArea URL.
    public static func checkWindowOrigin(
        windowTitle: String,
        documentURL: String = "",
        webAreaURL: String = "",
        extraOrigins: [String] = []
    ) -> BlindfoldDecision {
        let combined = "\(windowTitle) \(documentURL) \(webAreaURL)"
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .lowercased()
        if combined.isEmpty {
            return .allowed
        }
        if combined.contains("[blocked_secure_vault]")
            || combined.contains("[blocked_sensitive_origin]")
            || combined.contains("[blocked_system_security_surface]")
        {
            return BlindfoldDecision(
                blocked: true,
                category: .sensitiveWebOrigin,
                placeholderTitle: "[BLOCKED_SENSITIVE_ORIGIN]",
                reason: "BLOCKED: Window is marked as a protected vault or sensitive origin."
            )
        }
        for pat in (sensitiveWebOriginPatterns + extraOrigins.map { $0.lowercased() }) where !pat.isEmpty {
            if combined.contains(pat) {
                return BlindfoldDecision(
                    blocked: true,
                    category: .sensitiveWebOrigin,
                    placeholderTitle: "[BLOCKED_SENSITIVE_ORIGIN]",
                    reason: "BLOCKED: Window matches protected sensitive web origin '\(pat)'."
                )
            }
        }
        return .allowed
    }

    /// Return true if an AX element role/subrole represents a password or secure input field.
    public static func isSecureElement(role: String, subrole: String?, title: String = "") -> Bool {
        let rLow = role.lowercased()
        let sLow = (subrole ?? "").lowercased()
        if role == "AXSecureTextField" || subrole == "AXSecureTextField" {
            return true
        }
        if rLow.contains("secure") || rLow.contains("password") || sLow.contains("secure") || sLow.contains("password") {
            return true
        }
        return false
    }

    /// Sanitize text to neutralize newline breakouts, prompt-injection markers, and live credential tokens.
    public static func sanitizeDisplayString(_ raw: String?, maxLength: Int = 80) -> String {
        guard let raw, !raw.isEmpty else { return "" }
        if raw == "[REDACTED_PASSWORD]" {
            return raw
        }
        var cleaned = raw.replacingOccurrences(of: #"[\r\n\t]+"#, with: " ", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)
        cleaned = cleaned
            .replacingOccurrences(of: "[SYSTEM INSTRUCTION", with: "\\[SYSTEM_INSTRUCTION")
            .replacingOccurrences(of: "[SYSTEM", with: "\\[SYSTEM")
            .replacingOccurrences(of: "```", with: "")

        for rx in secretRegexes {
            let range = NSRange(cleaned.startIndex..<cleaned.endIndex, in: cleaned)
            cleaned = rx.stringByReplacingMatches(in: cleaned, options: [], range: range, withTemplate: "[REDACTED_SECRET]")
        }
        if cleaned.count > maxLength {
            return String(cleaned.prefix(maxLength))
        }
        return cleaned
    }

    /// Return true when NSPasteboard carries concealed/transient password-manager types.
    public static func isPasteboardConcealed(typeIdentifiers: [String]) -> Bool {
        for raw in typeIdentifiers {
            let low = raw.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
            if concealedPasteboardTypes.contains(low) || low.contains("concealedtype") || low.contains("onepassword") {
                return true
            }
        }
        return false
    }
}
